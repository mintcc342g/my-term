#!/bin/bash
# installers/codex.sh — Codex deployment of shared my-term settings

_codex_config_request() {
  local id="$1" method="$2" params="$3" line
  jq -cn --argjson id "$id" --arg method "$method" --argjson params "$params" \
    '{id: $id, method: $method, params: $params}' >&3 || return 1

  while IFS= read -r -t 10 line <&4; do
    if jq -e --argjson id "$id" '.id == $id' <<< "$line" >/dev/null; then
      if jq -e 'has("error")' <<< "$line" >/dev/null; then
        jq -r '.error.message' <<< "$line" >&2
        return 1
      fi
      jq -c '.result' <<< "$line"
      return
    fi
  done
  printf 'Codex did not respond to %s.\n' "$method" >&2
  return 1
}

_sync_codex_permissions() (
  local codex_home="$1" config rules tmp server_pid current version params
  umask 077
  mkdir -p "$codex_home" || return 1
  codex_home="$(cd "$codex_home" && pwd -P)" || return 1
  config="$codex_home/config.toml"
  rules="$codex_home/rules/my-term.rules"
  if [ -L "$config" ] || [ -L "$rules" ]; then
    printf 'Cannot update symlinked Codex permission files.\n' >&2
    return 1
  fi
  if [ -e "$rules" ] && [ "$(head -n 1 "$rules")" != "# Generated by my-term." ]; then
    printf 'Existing command rules are not managed by my-term: %s\n' "$rules" >&2
    return 1
  fi

  # Keep the app-server input open until the configuration write completes.
  tmp="$(mktemp -d "$codex_home/.permissions.XXXXXX")" || return 1
  trap '
    exec 3>&- 4<&-
    if [ -n "${server_pid:-}" ]; then
      kill "$server_pid" 2>/dev/null || true
      wait "$server_pid" 2>/dev/null || true
    fi
    rm -f "$tmp/input" "$tmp/output" "$tmp/my-term.rules"
    rmdir "$tmp"
  ' EXIT
  mkfifo "$tmp/input" "$tmp/output" || return 1
  cp "$SCRIPT_DIR/my-codex/rules/my-term.rules" "$tmp/my-term.rules" || return 1
  CODEX_HOME="$codex_home" codex app-server --listen stdio:// < "$tmp/input" > "$tmp/output" &
  server_pid=$!
  exec 3>"$tmp/input" 4<"$tmp/output"
  _codex_config_request 1 initialize '{"clientInfo":{"name":"my-term","version":"1"}}' >/dev/null || return 1
  printf '%s\n' '{"method":"initialized"}' >&3

  current="$(_codex_config_request 2 config/read '{"includeLayers":true}')" || return 1
  if jq -e '
    [.layers[] | select(.name.type == "user" and .name.profile == null)][0].config
    | has("sandbox_mode") or has("sandbox_workspace_write")
      or (has("default_permissions") and .default_permissions != "my-term")
      or (.permissions["my-term"] != null and .default_permissions != "my-term")
  ' <<< "$current" >/dev/null; then
    printf 'Codex already has a conflicting sandbox or permission profile: %s\n' "$config" >&2
    return 1
  fi

  version="$(jq -c '
    [.layers[] | select(.name.type == "user" and .name.profile == null)][0].version
  ' <<< "$current")" || return 1
  params="$(jq -c --arg home "$codex_home" --argjson version "$version" '
    (.edits[] | select(.keyPath == "permissions.my-term")).value.filesystem += {
      ($home + "/auth.json"): "deny",
      ($home + "/sessions"): "deny"
    }
    | .expectedVersion = $version
  ' "$SCRIPT_DIR/my-codex/settings/permissions.json")" || return 1
  mkdir -p "$(dirname "$rules")" || return 1
  _codex_config_request 3 config/batchWrite "$params" >/dev/null || return 1
  if ! cmp -s "$tmp/my-term.rules" "$rules"; then
    mv -f "$tmp/my-term.rules" "$rules" || return 1
  fi
)

_sync_codex_files() {
  local codex_home="${CODEX_HOME:-$HOME/.codex}"
  if [ -e "$codex_home/AGENTS.override.md" ] && [ -s "$codex_home/AGENTS.override.md" ]; then
    log_step "Codex AGENTS.override.md takes precedence over AGENTS.md."
  fi
  if [ -L "$codex_home/AGENTS.md" ]; then
    log_fail "Cannot update symlinked Codex instructions: $codex_home/AGENTS.md"
  else
    _sync_agent_instructions "$codex_home/AGENTS.md"
  fi

  if _sync_codex_permissions "$codex_home"; then
    log_done "Codex global permissions configured."
  else
    log_fail "Codex global permission profile could not be configured. See the details above."
  fi
}

_sync_codex_wiki() {
  local codex_home="${CODEX_HOME:-$HOME/.codex}"
  _sync_wiki_files "$1" "$codex_home/my-wiki"
  _set_codex_wiki_hook add
  _sync_wk_skill "$codex_home/my-wiki" "$HOME/.agents/skills/wk"
}

_set_codex_wiki_hook() (
  local action="$1" codex_home="${CODEX_HOME:-$HOME/.codex}"
  local settings="$codex_home/hooks.json" command source tmp
  printf -v command '/bin/bash %q' "$codex_home/my-wiki/wk-trigger.sh"
  if [ -L "$settings" ]; then
    log_fail "Cannot update symlinked Codex hooks: $settings"
    return 1
  fi
  source="$settings"
  if [ ! -f "$settings" ]; then
    [ "$action" = add ] || return 0
    source=/dev/null
  fi

  umask 077
  tmp="$(mktemp "$codex_home/.hooks.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  if jq -s --arg cmd "$command" --arg action "$action" '
    if length == 0 then {} elif length == 1 then .[0] else error("expected one JSON object") end
    | if type != "object" then error("expected hooks object") else . end
    | {type: "command", command: $cmd, statusMessage: "my-term wk"} as $handler
    | (.hooks.UserPromptSubmit // []) as $groups
    | if $action == "add" and any($groups[]?.hooks[]?; .command == $cmd) then
        (.hooks.UserPromptSubmit[]?.hooks[]?
          | select(.command == $cmd and ((.statusMessage // "") | test("^\\s*$")))).statusMessage = $handler.statusMessage
      elif $action == "add" then .hooks.UserPromptSubmit = ($groups + [{hooks: [$handler]}])
      elif any($groups[]?.hooks[]?; .command == $cmd) then
        .hooks.UserPromptSubmit = ($groups
          | map(.hooks |= map(select(.command != $cmd)))
          | map(select(.hooks | length > 0)))
        | if .hooks.UserPromptSubmit == [] then del(.hooks.UserPromptSubmit) else . end
      else .
      end
  ' "$source" > "$tmp"; then
    if ! cmp -s "$tmp" "$settings"; then
      mv -f "$tmp" "$settings"
      if [ "$action" = add ]; then
        log_done "Codex hook configured: my-term wk. Review it with /hooks in Codex."
      fi
    fi
  else
    log_fail "Could not update Codex hooks: $settings"
    return 1
  fi
)

_has_codex_files() {
  local codex_home="${CODEX_HOME:-$HOME/.codex}"
  [ -d "$codex_home/my-wiki" ] || _has_wk_skill "$HOME/.agents/skills/wk" ||
    grep -qF '<!-- MYTERM:OPTIONAL:' "$codex_home/AGENTS.md" 2>/dev/null
}

_delete_codex_files() {
  local codex_home="${CODEX_HOME:-$HOME/.codex}"
  local instructions="$codex_home/AGENTS.md" wiki="$codex_home/my-wiki"
  if [ ! -L "$instructions" ]; then
    md_remove_optional_blocks "$instructions"
  fi
  if _set_codex_wiki_hook remove && [ -d "$wiki" ] && [ ! -L "$wiki" ]; then
    rm -f "$wiki/wiki-path" "$wiki/wk-trigger.sh" "$wiki/wk-directive.md"
    rmdir "$wiki" 2>/dev/null || true
  fi
  _delete_wk_skill "$HOME/.agents/skills/wk"
}
